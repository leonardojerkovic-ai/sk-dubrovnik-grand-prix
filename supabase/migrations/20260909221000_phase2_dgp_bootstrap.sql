create or replace function public.player_is_dgp_member_on_date(p_player_id integer, p_on_date date)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(
    (select pm.is_member
       from public.player_memberships pm
      join public.seasons s on s.id=pm.season_id
      where pm.player_id=p_player_id
        and p_on_date between coalesce(pm.valid_from,s.start_date) and coalesce(pm.valid_to,s.end_date)
      order by pm.id desc limit 1),
    (select p.is_member from public.players p where p.id=p_player_id), false
  );
$$;

