create or replace function public.require_dgp_admin()
returns void language plpgsql security definer set search_path = '' as $$
declare v_role text;
begin
  select upper(up.role::text) into v_role from public.user_profiles up where up.id=auth.uid();
  if coalesce(v_role,'') not in ('ADMIN','SUPER_ADMIN') then
    raise exception 'Nedozvoljena radnja: samo administrator može izvršiti ovu radnju.';
  end if;
end;
$$;

create or replace function public.calculate_dgp_points(p_tournament_id integer)
returns table(player_id integer, final_rank integer, points_awarded numeric)
language plpgsql security definer set search_path = '' as $$
declare v_scoring_rule_id bigint; v_tournament_level text; v_tempo text; v_n integer; v_avg_rating numeric; v_fn numeric; v_fr numeric; v_fc numeric; v_ft numeric; v_total_factor numeric;
begin
  perform public.require_dgp_admin();
  select sr.id into v_scoring_rule_id from public.scoring_rules sr where sr.rule_code='DGP_2027' and sr.system_type='DUBROVNIK_GP' and sr.is_active=true limit 1;
  if v_scoring_rule_id is null then raise exception 'Aktivno DGP scoring pravilo nije pronađeno.'; end if;
  select upper(coalesce(t.tournament_level,'CLUB')), upper(coalesce(t.tempo,'STANDARD')) into v_tournament_level,v_tempo from public.tournaments t where t.id=p_tournament_id;
  if not found then raise exception 'Turnir % ne postoji.',p_tournament_id; end if;
  select count(*) into v_n from public.tournament_results tr where tr.tournament_id=p_tournament_id and coalesce(tr.games_played,0)>0;
  if v_n < 6 then
    update public.tournament_results set points_awarded=0, scoring_rule_id=v_scoring_rule_id, calculated_at=now(), updated_at=now() where tournament_id=p_tournament_id;
    return query select tr.player_id,tr.final_rank,0::numeric from public.tournament_results tr where tr.tournament_id=p_tournament_id order by tr.final_rank nulls last; return;
  end if;
  select avg(coalesce(tr.rating_used,1400)) into v_avg_rating from public.tournament_results tr where tr.tournament_id=p_tournament_id and coalesce(tr.games_played,0)>0;
  v_fn := round(least(1.50,0.80+0.16*log(2,v_n::numeric/7.0)),3);
  v_fr := round(greatest(0.80,least(1.30,1.00+(v_avg_rating-1750)*0.0008)),3);
  v_fc := case v_tournament_level when 'CLUB' then 1.00 when 'COMPETITIVE' then 1.25 when 'TOP' then 1.50 else 1.00 end;
  v_ft := case v_tempo when 'STANDARD' then 1.00 when 'RAPID' then 0.90 when 'BLITZ' then 0.75 else 1.00 end;
  v_total_factor := least(2.50,v_fn*v_fr*v_fc*v_ft);
  update public.tournament_results tr set points_awarded=case when coalesce(tr.games_played,0)<=0 or tr.final_rank is null then 0 else greatest(1,least(250,round(100*power(((v_n-tr.final_rank+1)::numeric/v_n::numeric),1.35)*v_total_factor))) end, scoring_rule_id=v_scoring_rule_id, calculated_at=now(), updated_at=now() where tr.tournament_id=p_tournament_id;
  return query select tr.player_id,tr.final_rank,tr.points_awarded from public.tournament_results tr where tr.tournament_id=p_tournament_id order by tr.final_rank nulls last;
end;
$$;

create or replace function public.update_dgp_result(p_result_id bigint,p_final_rank integer,p_score numeric,p_games_played integer,p_wins integer,p_draws integer,p_losses integer)
returns public.tournament_results language plpgsql security definer set search_path = '' as $$
declare v_row public.tournament_results;
begin
  perform public.require_dgp_admin();
  if p_final_rank is not null and p_final_rank<1 then raise exception 'Konačni rang mora biti pozitivan broj.'; end if;
  if p_score is not null and p_score<0 then raise exception 'Rezultat (score) ne može biti negativan.'; end if;
  if coalesce(p_games_played,0)<0 or coalesce(p_wins,0)<0 or coalesce(p_draws,0)<0 or coalesce(p_losses,0)<0 then raise exception 'Broj partija, pobjeda, remija i poraza ne može biti negativan.'; end if;
  update public.tournament_results set final_rank=p_final_rank,score=p_score,games_played=p_games_played,wins=coalesce(p_wins,0),draws=coalesce(p_draws,0),losses=coalesce(p_losses,0),updated_at=now() where id=p_result_id returning * into v_row;
  if not found then raise exception 'Rezultat % ne postoji.',p_result_id; end if;
  perform public.calculate_dgp_points(v_row.tournament_id);
  select * into v_row from public.tournament_results where id=p_result_id;
  return v_row;
end;
$$;

create or replace view public.dgp_general_ranking as
with quota as (
  select greatest(5,ceil(count(*)::numeric/2.0)::integer) quota
  from public.tournaments t join public.seasons s on s.id=t.season_id
  where s.code='DGP-2027' and t.tournament_scope='GENERAL' and t.event_stage='REGULAR'
), regular_rows as (
  select tr.player_id,tr.points_awarded,tr.final_rank,tr.tournament_id,
         row_number() over(partition by tr.player_id order by tr.points_awarded desc,tr.final_rank,tr.tournament_id) rn
  from public.tournament_results tr join public.tournaments t on t.id=tr.tournament_id join public.seasons s on s.id=t.season_id
  where s.code='DGP-2027' and t.tournament_scope='GENERAL' and t.event_stage='REGULAR' and tr.games_played>0 and tr.points_awarded>0
), regular_agg as (
  select rr.player_id,sum(rr.points_awarded) filter(where rr.rn<=q.quota) regular_points,
         array_agg(rr.points_awarded order by rr.points_awarded desc,rr.final_rank,rr.tournament_id) filter(where rr.rn<=q.quota) regular_tiebreak,
         count(*) filter(where rr.rn<=q.quota) counted_regular
  from regular_rows rr cross join quota q group by rr.player_id,q.quota
), finals as (
  select tr.player_id,sum(tr.points_awarded) final_points,
         array_agg(tr.points_awarded order by tr.points_awarded desc,tr.final_rank,tr.tournament_id) final_tiebreak
  from public.tournament_results tr join public.tournaments t on t.id=tr.tournament_id join public.seasons s on s.id=t.season_id
  where s.code='DGP-2027' and t.tournament_scope='GENERAL' and t.event_stage='FINAL' and tr.games_played>0 and tr.points_awarded>0 group by tr.player_id
)
select p.id player_id,p.full_name,(coalesce(r.regular_points,0)+coalesce(f.final_points,0)) general_gp_points,
       coalesce(r.counted_regular,0)+case when coalesce(f.final_points,0)>0 then 1 else 0 end counted_results,
       coalesce(r.regular_tiebreak,array[]::numeric[])||coalesce(f.final_tiebreak,array[]::numeric[]) regular_tiebreak,
       coalesce(f.final_points,0) final_points
from public.players p left join regular_agg r on r.player_id=p.id left join finals f on f.player_id=p.id where p.is_active=true;

create or replace view public.dgp_category_ranking as
with categories as (select category_code from public.scoring_categories where category_type='SPECIAL_CATEGORY' and is_active=true),
eligible as (
 select c.category_code,tr.player_id,tr.tournament_id,tr.points_awarded,tr.final_rank,
        row_number() over(partition by c.category_code,tr.player_id order by tr.points_awarded desc,tr.final_rank,tr.tournament_id) rn
 from categories c join public.tournament_results tr on true join public.tournaments t on t.id=tr.tournament_id join public.seasons s on s.id=t.season_id
 join public.players p on p.id=tr.player_id
 where s.code='DGP-2027' and t.event_stage='REGULAR' and tr.games_played>0 and tr.points_awarded>0 and p.is_active=true
   and ((c.category_code='WOMEN' and p.gender in ('F','Ž','FEMALE')) or (c.category_code='U20' and 2027-p.birth_year<=20) or (c.category_code='U16' and 2027-p.birth_year<=16) or (c.category_code='U12' and 2027-p.birth_year<=12) or (c.category_code='S50' and 2027-p.birth_year>=50) or (c.category_code='S65' and 2027-p.birth_year>=65) or (c.category_code='U1800' and coalesce(tr.rating_used,tr.rating_rapid,tr.rating_standard,tr.rating_blitz)<1800))
), counted as (
 select e.*,greatest(5,ceil(count(*) over(partition by e.category_code)::numeric/2.0)::integer) quota from eligible e
), agg as (
 select category_code,player_id,sum(points_awarded) filter(where rn<=quota) category_special_points,count(*) filter(where rn<=quota) counted_special_results,max(quota) quota,
        array_agg(points_awarded order by points_awarded desc) filter(where rn<=quota) special_tiebreak from counted group by category_code,player_id
)
select a.category_code,a.player_id,p.full_name,coalesce(g.general_gp_points,0)+coalesce(a.category_special_points,0) category_gp_points,
       coalesce(g.general_gp_points,0) general_gp_points,coalesce(a.category_special_points,0) category_special_points,a.counted_special_results,
       a.quota,a.special_tiebreak,0::numeric eligible_final_points
from agg a join public.players p on p.id=a.player_id left join public.dgp_general_ranking g on g.player_id=a.player_id;

